def post_page(p, prev_p, next_p, more):
    url = f"{SITE}/blog/{p['slug']}/"
    image = SITE + p["cover"] if p["cover"].startswith("/") else (p["cover"] or SITE + "/showcase/img/og.jpg")
    ld = {
        "@context": "https://schema.org", "@type": "BlogPosting", "headline": p["title"],
        "description": p["excerpt"], "datePublished": p["date"].isoformat(), "image": image,
        "author": {"@type": "Person", "name": AUTHOR, "url": SITE + "/"}, "mainEntityOfPage": url,
        "keywords": ", ".join(p["tags"]), "wordCount": p["words"],
    }
    extra = (f'<meta property="article:published_time" content="{p["date"].isoformat()}" />\n  '
             f'<script type="application/ld+json">{json.dumps(ld, ensure_ascii=False)}</script>\n  ')
    toc = "".join(f'<li><a href="#{esc(t["id"])}">{esc(html.unescape(t["name"]))}</a></li>' for t in p["toc"])
    tags = "".join(f"<li>{esc(t)}</li>" for t in p["tags"])
    share_url = esc(url)
    share_title = esc(p["title"])
    nav = ""
    if prev_p or next_p:
        nav = '<nav class="post-nav" aria-label="More posts">'
        nav += (f'<a class="prev" href="/blog/{esc(prev_p["slug"])}/"><small>Newer</small><b>{esc(prev_p["title"])}</b></a>' if prev_p else "<span></span>")
        nav += (f'<a class="next" href="/blog/{esc(next_p["slug"])}/"><small>Older</small><b>{esc(next_p["title"])}</b></a>' if next_p else "<span></span>")
        nav += "</nav>"
