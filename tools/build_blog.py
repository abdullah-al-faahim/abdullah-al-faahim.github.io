def index_page(posts):
    counts = {c: sum(1 for p in posts if p["category"] == c) for c in CATEGORIES}
    chips = [f'<button type="button" data-c="all" aria-pressed="true">All posts<small>{len(posts)}</small></button>']
    chips += [f'<button type="button" data-c="{c}" aria-pressed="false">{esc(n)}<small>{counts[c]}</small></button>' for c, n in CATEGORIES.items() if counts[c]]
    lead, rest = (posts[0], posts[1:]) if posts else (None, [])
    lead_html = card(lead, "post-card lead") if lead else '<p class="empty">No posts yet.</p>'
    grid = "".join(card(p) for p in rest)
    desc = "Notes on broadcast technology, app development, design systems, brand identity, design research, leadership and AI for design by Abdullah Al Fahim."
    return head(f"Blog · {AUTHOR}", desc, f"{SITE}/blog/", SITE + "/showcase/img/og.jpg") + f"""
  <main id="main">
    <section class="blog-hero">
      <div class="wrap">
        <span class="kicker"><i></i>Blog</span>
        <h1>Notes on broadcast, apps <em>and design.</em></h1>
        <p>What I learn keeping a TV channel on air, building apps for Bangladesh and designing brands, written down so it&#8217;s useful to someone else.</p>
      </div>
    </section>
    <section class="blog-list">
      <div class="wrap">
        <div class="filters" id="postFilters" role="group" aria-label="Filter posts by topic">{"".join(chips)}</div>
        <div class="post-lead">{lead_html}</div>
        <div class="post-grid three" id="postGrid">{grid}</div>
      </div>
    </section>
  </main>
""" + FOOT


def feed(posts):
    items = "".join(
        f"""
    <item>
      <title>{esc(p["title"])}</title>
      <link>{SITE}/blog/{p["slug"]}/</link>
      <guid>{SITE}/blog/{p["slug"]}/</guid>
      <pubDate>{format_datetime(dt.datetime.combine(p["date"], dt.time(9, 0), dt.timezone(dt.timedelta(hours=6))))}</pubDate>
      <category>{esc(CATEGORIES[p["category"]])}</category>
      <description>{esc(p["excerpt"])}</description>
    </item>""" for p in posts[:30])
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0">
  <channel>
    <title>{AUTHOR} · Blog</title>
    <link>{SITE}/blog/</link>
    <description>Broadcast technology, app development, design systems, brand identity, research, leadership and AI for design.</description>
    <language>en</language>{items}
  </channel>
</rss>
"""


def sitemap(posts):
    urls = [(SITE + "/", None), (SITE + "/blog/", posts[0]["date"] if posts else None)]
    urls += [(f"{SITE}/blog/{p['slug']}/", p["date"]) for p in posts]
    rows = "".join(f"\n  <url><loc>{u}</loc>" + (f"<lastmod>{d.isoformat()}</lastmod>" if d else "") + "</url>" for u, d in urls)
    return f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">{rows}\n</urlset>\n'


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main():
    posts = [p for p in (parse(f) for f in sorted(SRC.glob("*.md"))) if p]
    posts.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)
    slugs = {p["slug"] for p in posts}
    if len(slugs) != len(posts):
        raise SystemExit("Two posts share a slug")

    # Remove pages of posts that were deleted or turned back into drafts
    if OUT.exists():
        for d in OUT.iterdir():
            page = d / "index.html"
            if d.is_dir() and d.name not in slugs and page.exists() and MARK in page.read_text(encoding="utf-8"):
                shutil.rmtree(d)

    for i, p in enumerate(posts):
        prev_p = posts[i - 1] if i > 0 else None
        next_p = posts[i + 1] if i + 1 < len(posts) else None
        same = [q for q in posts if q is not p and q["category"] == p["category"]]
        others = [q for q in posts if q is not p and q not in same]
        write(OUT / p["slug"] / "index.html", post_page(p, prev_p, next_p, (same + others)[:3]))
    write(OUT / "index.html", index_page(posts))
    write(OUT / "feed.xml", feed(posts))
    write(ROOT / "sitemap.xml", sitemap(posts))
    write(OUT / "posts.json", json.dumps([
        {"slug": p["slug"], "title": p["title"], "date": p["date"].isoformat(), "category": p["category"],
         "categoryLabel": CATEGORIES[p["category"]], "excerpt": p["excerpt"], "cover": p["cover"], "minutes": p["minutes"]}
        for p in posts], ensure_ascii=False, indent=1) + "\n")

    # Home page: the four newest posts between the BLOG markers
    home = ROOT / "index.html"
    if home.exists():
        text = home.read_text(encoding="utf-8")
        m = re.search(r"<!-- BLOG:START -->.*?<!-- BLOG:END -->", text, re.S)
        if m:
            block = "<!-- BLOG:START -->" + "".join(card(p, "post-card rv") for p in posts[:4]) + "<!-- BLOG:END -->"
            text = text[:m.start()] + block + text[m.end():]
            write(home, text)
    print(f"Built {len(posts)} posts")


if __name__ == "__main__":
    main()
