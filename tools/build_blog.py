# ---------------------------------------------------------------- reading posts
def parse(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n(.*)$", text, re.S)
    if not m:
        raise SystemExit(f"{path.name}: missing front matter")
    meta = yaml.safe_load(m.group(1)) or {}
    body = m.group(2)
    if meta.get("draft"):
        return None
    for key in ("title", "date", "category"):
        if not meta.get(key):
            raise SystemExit(f"{path.name}: missing '{key}'")
    date = meta["date"]
    if isinstance(date, str):
        date = dt.datetime.fromisoformat(date.replace("Z", "+00:00"))
    if isinstance(date, dt.datetime):
        date = date.date()
    category = str(meta["category"])
    if category not in CATEGORIES:
        raise SystemExit(f"{path.name}: unknown category '{category}' (use one of {', '.join(CATEGORIES)})")
    md = markdown.Markdown(extensions=["extra", "toc", "sane_lists", "smarty"])
    body_html = md.convert(body)
    # Images in posts: lazy, async, and wrapped tables scroll on phones
    body_html = body_html.replace("<img ", '<img loading="lazy" decoding="async" ')
    body_html = body_html.replace("<table>", '<div class="table-wrap"><table>').replace("</table>", "</table></div>")
    words = len(re.findall(r"\w+", re.sub(r"<[^>]+>", " ", body_html)))
    tags = meta.get("tags") or []
    if isinstance(tags, str):
        tags = [t.strip() for t in tags.split(",") if t.strip()]
    slug = str(meta.get("slug") or path.stem)
    return {
        "slug": slug,
        "title": str(meta["title"]),
        "date": date,
        "category": category,
        "excerpt": str(meta.get("excerpt") or ""),
        "cover": str(meta.get("cover") or ""),
        "cover_alt": str(meta.get("cover_alt") or ""),
        "tags": [str(t) for t in tags],
        "html": body_html,
        "toc": md.toc_tokens,
        "minutes": max(1, math.ceil(words / 220)),
        "words": words,
    }


def nice_date(d):
    return f"{d.day} {d.strftime('%b %Y')}"


