def card(p, cls="post-card"):
    img = (f'<span class="pc-im"><img src="{esc(p["cover"])}" alt="" width="1600" height="900" loading="lazy" decoding="async" /></span>'
           if p["cover"] else '<span class="pc-im pc-blank"></span>')
    return (f'<a class="{cls}" href="/blog/{esc(p["slug"])}/" data-cat="{esc(p["category"])}">{img}'
            f'<span class="pc-meta"><span class="pc-cat">{esc(CATEGORIES[p["category"]])}</span><time datetime="{p["date"].isoformat()}">{nice_date(p["date"])}</time></span>'
            f'<b>{esc(p["title"])}</b><small>{esc(p["excerpt"])}</small><span class="pc-read">{p["minutes"]} min read</span></a>')


