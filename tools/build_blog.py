"""Build the blog from Markdown.

Posts live in content/blog/<slug>.md (written by hand or in the CMS at /admin/).
This script writes:
  blog/index.html            the blog home, newest first, with category filters
  blog/<slug>/index.html     one page per post
  blog/posts.json            post list for anything else that needs it
  blog/feed.xml              RSS feed
  sitemap.xml                home page plus every post
and fills the "From the blog" section of index.html (between the BLOG markers)
with the four newest posts.

Posts with `draft: true` are skipped. Needs:  pip install markdown pyyaml
Run from anywhere:  python tools/build_blog.py
The GitHub Action in .github/workflows/blog.yml runs it on every change to content/blog/.
"""

